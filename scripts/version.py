#!/usr/bin/env python3
"""Resolve the RotaryCAM version from the main repo's git tags (pipe-macos).

The landing repo (`pipe-landing`) is published separately and does not carry its
own release tags. The product version is the latest `vMAJOR.MINOR.PATCH` tag on
the main `pipe-macos` repo, read here via `git ls-remote`. Override with the
`ROTARYCAM_VERSION` env var for offline/deterministic builds.

Usage:
  python3 scripts/version.py --print                 # -> "0.2.4 v0.2.4-BETA"
  python3 scripts/version.py --write-js version.js   # -> writes window.ROTARYCAM_VERSION*
"""
import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

MAIN_REMOTE = "https://github.com/nicolai86/pipe-macos.git"
ROOT = Path(__file__).resolve().parent.parent
TAG_RE = re.compile(r"^refs/tags/v(\d+)\.(\d+)\.(\d+)$")
FALLBACK = "0.0.0-dev"


def resolve_version(remote=MAIN_REMOTE):
    env = os.environ.get("ROTARYCAM_VERSION", "").strip()
    if env:
        return env.lstrip("v")

    try:
        out = subprocess.check_output(
            ["git", "ls-remote", "--refs", "--tags", remote, "refs/tags/v*"],
            text=True,
            stderr=subprocess.DEVNULL,
        )
    except Exception:
        return FALLBACK

    candidates = []
    for line in out.splitlines():
        fields = line.split()
        if len(fields) != 2:
            continue
        m = TAG_RE.match(fields[1].replace("^{}", ""))
        if m:
            candidates.append(tuple(int(x) for x in m.groups()))

    if not candidates:
        return FALLBACK
    return ".".join(map(str, max(candidates)))


def beta_label(version):
    return f"v{version}-BETA"


def write_js(path):
    v = resolve_version()
    content = (
        "// Auto-generated by scripts/version.py. Do not edit by hand.\n"
        f"window.ROTARYCAM_VERSION = \"{v}\";\n"
        f"window.ROTARYCAM_VERSION_BETA = \"{beta_label(v)}\";\n"
    )
    Path(path).write_text(content, encoding="utf-8")
    print(f"[stamp] Wrote {path}: v{v}-BETA")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write-js", metavar="PATH", default=str(ROOT / "version.js"))
    ap.add_argument("--print", action="store_true")
    args = ap.parse_args()

    if args.print:
        v = resolve_version()
        print(f"{v} {beta_label(v)}")
    else:
        write_js(args.write_js)
    return 0


if __name__ == "__main__":
    sys.exit(main())
